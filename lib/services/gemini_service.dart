import 'dart:convert';
import 'dart:io';
import 'package:http/http.dart' as http;
import 'package:shared_preferences/shared_preferences.dart';
import '../models/account_mapping.dart';
import '../models/upi_transaction.dart';
import 'mapping_service.dart';
import 'upi_extractor_service.dart';

class GeminiService {
  static const String _apiKeyPref = 'gemini_api_key_v1';
  static const String _geminiModelPref = 'gemini_model_name_v1';
  static const String _engineModePref = 'extraction_engine_mode_v1'; // 'local', 'gemini', 'groq'
  static const String defaultModel = 'gemini-3.6-flash';

  static Future<String?> getApiKey() async {
    final prefs = await SharedPreferences.getInstance();
    return prefs.getString(_apiKeyPref);
  }

  static Future<void> saveApiKey(String key) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_apiKeyPref, key.trim());
  }

  static Future<String> getModel() async {
    final prefs = await SharedPreferences.getInstance();
    return prefs.getString(_geminiModelPref) ?? defaultModel;
  }

  static Future<void> saveModel(String model) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_geminiModelPref, model.trim());
  }

  static Future<String> getEngineMode() async {
    final prefs = await SharedPreferences.getInstance();
    return prefs.getString(_engineModePref) ?? 'groq';
  }

  static Future<void> saveEngineMode(String mode) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_engineModePref, mode);
  }

  /// Normalize user input model name (e.g. "3.6flash" -> "gemini-3.6-flash")
  static String normalizeModelName(String raw) {
    String clean = raw.trim();
    if (clean.isEmpty) return defaultModel;
    if (!clean.startsWith('gemini-') && !clean.startsWith('models/')) {
      clean = 'gemini-$clean';
    }
    return clean;
  }

  /// Extract using Gemini Multimodal Vision API
  static Future<UpiTransaction> extractWithGemini(
    String imagePath,
    List<AccountMapping> mappings,
    String apiKey, {
    String? modelOverride,
  }) async {
    final rawModel = modelOverride ?? await getModel();
    final modelName = normalizeModelName(rawModel);

    final file = File(imagePath);
    final bytes = await file.readAsBytes();
    final base64Image = base64Encode(bytes);

    final String mimeType = imagePath.toLowerCase().endsWith('.png') ? 'image/png' : 'image/jpeg';

    final uri = Uri.parse(
      'https://generativelanguage.googleapis.com/v1beta/models/$modelName:generateContent?key=$apiKey',
    );

    const promptText = '''
You are an expert UPI receipt OCR system for Indian payments (PhonePe, Google Pay, Paytm, etc.).
Extract the exact data into JSON format:
{
  "date": "Date formatted strictly as dd-MM-yyyy (e.g. 22-11-2026)",
  "app": "UPI app name (e.g. PhonePe, Google Pay, Paytm)",
  "name": "Exact Payee or Recipient full name",
  "id": "Transaction ID or UTR number",
  "msg": "Payment message or note (e.g. 'advance salary')",
  "amount": numeric base purchase/recharge amount (e.g. 548 if itemized, or total debited amount),
  "charges": numeric sum of all extra fees/charges (e.g. Service fee + Convenience fee = 11.46, or 0 if no extra fees),
  "direction": "OUT" if paid/debited else "IN",
  "account_digits": "last 2 to 4 digits of debited/credited account, e.g. 9989"
}
Return ONLY valid JSON.
''';

    final body = json.encode({
      "contents": [
        {
          "parts": [
            {"text": promptText},
            {
              "inline_data": {
                "mime_type": mimeType,
                "data": base64Image,
              }
            }
          ]
        }
      ],
      "generationConfig": {
        "temperature": 0.1,
        "response_mime_type": "application/json"
      }
    });

    final response = await http.post(
      uri,
      headers: {'Content-Type': 'application/json'},
      body: body,
    );

    if (response.statusCode != 200) {
      throw Exception('Gemini API Error (${response.statusCode}): ${response.body}');
    }

    final data = json.decode(response.body);
    final candidates = data['candidates'] as List?;
    if (candidates == null || candidates.isEmpty) {
      throw Exception('No response generated by Gemini.');
    }

    String contentText = candidates[0]['content']['parts'][0]['text'] ?? '';
    contentText = contentText.replaceAll(RegExp(r'^```json\s*|```\s*$'), '').trim();

    final Map<String, dynamic> parsed = json.decode(contentText);

    final String date = parsed['date'] ?? '';
    final String app = parsed['app'] ?? 'UPI';
    final String name = parsed['name'] ?? '';
    final String id = parsed['id'] ?? '';
    final String msg = parsed['msg'] ?? '';
    final double amount = (parsed['amount'] is num) ? (parsed['amount'] as num).toDouble() : 0.0;
    final double charges = (parsed['charges'] is num) ? (parsed['charges'] as num).toDouble() : 0.0;
    final String rawDir = (parsed['direction'] ?? 'OUT').toString().replaceAll(RegExp(r'[🔴🟢]'), '').trim();
    final String direction = rawDir.toUpperCase().contains('IN') ? 'IN' : 'OUT';
    final String accDigits = parsed['account_digits']?.toString() ?? '';

    // Apply custom user mapping for account name & Type (UPI vs Credit)
    String account = "Other Account";
    String type = "UPI";
    if (accDigits.isNotEmpty) {
      final matchedMapping = MappingService.matchAccount(accDigits, mappings);
      if (matchedMapping != null) {
        account = matchedMapping.accountName;
        type = matchedMapping.type;
      } else {
        account = "Account ending in $accDigits";
      }
    }

    final category = UpiExtractorService.categorizeByMessage(msg, name: name);

    return UpiTransaction(
      date: date,
      app: app,
      name: name,
      id: id,
      msg: msg,
      amount: amount,
      charges: charges,
      direction: direction,
      type: type,
      account: account,
      category: category,
      rawText: contentText,
    );
  }
}
