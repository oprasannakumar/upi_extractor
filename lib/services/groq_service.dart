import 'dart:convert';
import 'dart:io';
import 'package:http/http.dart' as http;
import 'package:shared_preferences/shared_preferences.dart';
import '../models/account_mapping.dart';
import '../models/upi_transaction.dart';
import 'mapping_service.dart';
import 'upi_extractor_service.dart';

class GroqService {
  static const String _groqApiKeyPref = 'groq_api_key_v1';
  static const String _groqModelPref = 'groq_model_name_v1';
  static const String defaultModel = 'qwen/qwen3.8-27b';

  static Future<String?> getApiKey() async {
    final prefs = await SharedPreferences.getInstance();
    return prefs.getString(_groqApiKeyPref);
  }

  static Future<void> saveApiKey(String key) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_groqApiKeyPref, key.trim());
  }

  static Future<String> getModel() async {
    final prefs = await SharedPreferences.getInstance();
    return prefs.getString(_groqModelPref) ?? defaultModel;
  }

  static Future<void> saveModel(String model) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_groqModelPref, model.trim());
  }

  /// Extract using Groq API (supports vision if model allows, or intelligent OCR text reasoning)
  static Future<UpiTransaction> extractWithGroq(
    String imagePath,
    List<AccountMapping> mappings,
    String apiKey, {
    String? modelOverride,
  }) async {
    final model = modelOverride ?? await getModel();
    final file = File(imagePath);
    final bytes = await file.readAsBytes();
    final base64Image = base64Encode(bytes);

    // Also run fast local OCR so we have fallback text ready if model is text-only
    String ocrText = '';
    try {
      final localTx = await UpiExtractorService.extractFromImage(imagePath, mappings);
      ocrText = localTx.rawText ?? '';
    } catch (_) {}

    const systemPrompt = '''
You are an expert Indian UPI receipt data extractor for PhonePe, Google Pay, Paytm, etc.
Extract the transaction details into pure JSON:
{
  "date": "Date strictly formatted as dd-MM-yyyy (e.g. 22-11-2026)",
  "app": "UPI app name (e.g. PhonePe, Google Pay, Paytm)",
  "name": "Full Payee / Recipient or Sender name",
  "id": "Transaction ID or UTR number",
  "msg": "Payment message or note (e.g. 'advance salary')",
  "amount": numeric base purchase/recharge amount (e.g. 548 if itemized, or total debited amount),
  "charges": numeric sum of all extra fees/charges (e.g. Service fee + Convenience fee = 11.46, or 0 if no extra fees),
  "direction": "OUT" if paid/debited else "IN",
  "account_digits": "last 2 to 4 digits of debited/credited account, e.g. 9989"
}
Output ONLY valid JSON.
''';

    final uri = Uri.parse('https://api.groq.com/openai/v1/chat/completions');

    // Attempt 1: Try vision multimodal format with image_url
    Map<String, dynamic> requestBody = {
      "model": model,
      "messages": [
        {"role": "system", "content": systemPrompt},
        {
          "role": "user",
          "content": [
            {"type": "text", "text": "Extract UPI receipt details from this image:"},
            {
              "type": "image_url",
              "image_url": {"url": "data:image/jpeg;base64,$base64Image"}
            }
          ]
        }
      ],
      "response_format": {"type": "json_object"},
      "temperature": 0.1,
    };

    http.Response response = await http.post(
      uri,
      headers: {
        'Content-Type': 'application/json',
        'Authorization': 'Bearer $apiKey',
      },
      body: json.encode(requestBody),
    );

    // If multimodal fails (e.g. model doesn't support image input like text-only Qwen models),
    // Fallback immediately to feeding the OCR text into Qwen!
    if (response.statusCode != 200 && ocrText.isNotEmpty) {
      requestBody = {
        "model": model,
        "messages": [
          {"role": "system", "content": systemPrompt},
          {
            "role": "user",
            "content": "Extract the UPI receipt details from this OCR text:\n\n$ocrText"
          }
        ],
        "response_format": {"type": "json_object"},
        "temperature": 0.1,
      };

      response = await http.post(
        uri,
        headers: {
          'Content-Type': 'application/json',
          'Authorization': 'Bearer $apiKey',
        },
        body: json.encode(requestBody),
      );
    }

    if (response.statusCode != 200) {
      throw Exception('Groq API Error (${response.statusCode}): ${response.body}');
    }

    final data = json.decode(response.body);
    final choices = data['choices'] as List?;
    if (choices == null || choices.isEmpty) {
      throw Exception('No response generated by Groq.');
    }

    String contentText = choices[0]['message']['content'] ?? '';
    contentText = contentText.replaceAll(RegExp(r'^```json\s*|```\s*$'), '').trim();

    final Map<String, dynamic> parsed = json.decode(contentText);

    final String date = parsed['date'] ?? '';
    final String app = parsed['app'] ?? 'UPI';
    final String name = parsed['name'] ?? '';
    final String id = parsed['id'] ?? '';
    final String msg = parsed['msg'] ?? '';
    final double amount = (parsed['amount'] is num) ? (parsed['amount'] as num).toDouble() : 0.0;
    final double charges = (parsed['charges'] is num) ? (parsed['charges'] as num).toDouble() : 0.0;
    final String rawDir = (parsed['direction'] ?? 'OUT').toString().replaceAll(RegExp(r'[🔴🟢]'), '').trim();
    final String direction = rawDir.toUpperCase().contains('IN') ? 'IN' : 'OUT';
    final String accDigits = parsed['account_digits']?.toString() ?? '';

    // Apply custom user mapping for account name & Type
    String account = "Other Account";
    String type = "UPI";
    if (accDigits.isNotEmpty) {
      final matchedMapping = MappingService.matchAccount(accDigits, mappings);
      if (matchedMapping != null) {
        account = matchedMapping.accountName;
        type = matchedMapping.type;
      } else {
        account = "Account ending in $accDigits";
      }
    }

    final category = UpiExtractorService.categorizeByMessage(msg, name: name);

    return UpiTransaction(
      date: date,
      app: app,
      name: name,
      id: id,
      msg: msg,
      amount: amount,
      charges: charges,
      direction: direction,
      type: type,
      account: account,
      category: category,
      rawText: contentText,
    );
  }
}
